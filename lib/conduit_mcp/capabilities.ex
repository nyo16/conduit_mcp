defmodule ConduitMcp.Capabilities do
  @moduledoc """
  Builds the `capabilities` object a server advertises to MCP clients.

  The base set comes from the server module's `__capabilities__/0` when it
  defines one (typically generated by `ConduitMcp.Endpoint`); otherwise it is
  the plain `tools`/`resources`/`prompts` set with `listChanged: false`.

  Flags for optional features are then overlaid according to which callbacks
  the server module exports:

    * `resources.subscribe: true` — `handle_subscribe_resource/2`, and only
      when the base set advertises `resources` at all.
    * `completions: %{}` — `handle_complete/3`.
    * `logging: %{}` — `handle_set_log_level/2`.

  Used for the `initialize` reply.
  """

  alias ConduitMcp.ServerMeta

  @doc """
  Returns the capabilities map advertised for `server_module`.

  ## Examples

      ConduitMcp.Capabilities.build(MyServer)
      #=> %{
      #     "tools" => %{"listChanged" => false},
      #     "resources" => %{"listChanged" => false},
      #     "prompts" => %{"listChanged" => false}
      #   }
  """
  @spec build(module()) :: map()
  def build(server_module) do
    server_module
    |> base()
    |> maybe_put_subscribe(server_module)
    |> maybe_put_completions(server_module)
    |> maybe_put_logging(server_module)
  end

  defp base(server_module) do
    if ServerMeta.has?(server_module, :capabilities) do
      server_module.__capabilities__()
    else
      %{
        "tools" => %{"listChanged" => false},
        "resources" => %{"listChanged" => false},
        "prompts" => %{"listChanged" => false}
      }
    end
  end

  defp maybe_put_subscribe(caps, server_module) do
    if ServerMeta.has?(server_module, :subscribe) and Map.has_key?(caps, "resources") do
      Map.update!(caps, "resources", &Map.put(&1, "subscribe", true))
    else
      caps
    end
  end

  defp maybe_put_completions(caps, server_module) do
    if ServerMeta.has?(server_module, :complete) do
      Map.put(caps, "completions", %{})
    else
      caps
    end
  end

  defp maybe_put_logging(caps, server_module) do
    if ServerMeta.has?(server_module, :set_log_level) do
      Map.put(caps, "logging", %{})
    else
      caps
    end
  end
end
