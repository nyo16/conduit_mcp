defmodule ConduitMcp.Discover do
  @moduledoc """
  Builds the result of `server/discover`, the modern-era method a client uses
  to learn which protocol versions, capabilities and instructions a server
  has, without a handshake.

  `server/discover` is era-exempt: it is served on the modern path even when
  the request carries no `_meta` (see `ConduitMcp.Era`), because a client may
  call it precisely to find out which era the server speaks. It is
  authenticated like every other POST.

  The result body is:

    * `"supportedVersions"` — `ConduitMcp.Protocol.supported_versions/0`,
      modern and legacy versions newest first;
    * `"capabilities"` — `ConduitMcp.Capabilities.build/2` with `era:
      :modern`, the same set the legacy `initialize` result advertises
      (minus `resources.subscribe`);
    * `"instructions"` — see `instructions/2`; omitted when there are none.

  `ConduitMcp.Protocol.Modern` adds `resultType`, the cache hints and the
  `serverInfo` `_meta`.
  """

  alias ConduitMcp.Capabilities
  alias ConduitMcp.Protocol
  alias ConduitMcp.ServerMeta

  @doc """
  The `server/discover` result body for `server_module` on `conn`.
  """
  @spec result(module(), Plug.Conn.t() | map()) :: map()
  def result(server_module, conn) do
    %{
      "supportedVersions" => Protocol.supported_versions(),
      "capabilities" => Capabilities.build(server_module, era: :modern)
    }
    |> put_instructions(instructions(server_module, conn))
  end

  @doc """
  The server's instructions, or `nil`.

  The transport's `:instructions` option (resolved into
  `conn.private[:instructions]`) wins; otherwise the server module's
  `__instructions__/0`, generated by `use ConduitMcp.Server, instructions:`
  and by `use ConduitMcp.Endpoint, instructions:`. Only a string counts.
  Used for both `server/discover` and the legacy `initialize` result.
  """
  @spec instructions(module(), Plug.Conn.t() | map()) :: String.t() | nil
  def instructions(server_module, conn),
    do: string_or_nil(from_transport(conn) || from_module(server_module))

  defp from_transport(%{private: %{instructions: instructions}}), do: instructions
  defp from_transport(_conn), do: nil

  defp from_module(server_module) do
    if ServerMeta.has?(server_module, :instructions),
      do: server_module.__instructions__(),
      else: nil
  end

  defp string_or_nil(value) when is_binary(value), do: value
  defp string_or_nil(_value), do: nil

  defp put_instructions(result, nil), do: result
  defp put_instructions(result, instructions), do: Map.put(result, "instructions", instructions)
end
